import SwiftUI
import UIKit

/// 品牌视觉基准：**唯一**的品牌强调色定义处。
///
/// ## 为什么有这一层
/// 改造前全应用没有任何品牌色 —— 强调色一律是系统默认蓝（HIG §17「到处默认蓝」），
/// 再散落成 `Color.accentColor` / `.tint(.green)` 各写各的。
/// 现在品牌强调色只在这里定义一次，其余文件引用 `AppTheme.accent`，
/// 不在视图里另写色值（§15 设计令牌）。
///
/// ## 取值：Apple 蓝家族的明暗两版 `#0066CC` / `#0A84FF`
/// owner 明确指定「亮色暗色都用 Apple 风格的蓝色强调色」，所以色相锁在 `systemBlue`
/// 那一系（`#007AFF` 色相 ≈ 211°），不偏靛蓝、不偏青蓝，也**不做紫 → 蓝渐变**
/// （§2 禁用，单一实色）。这是**有意指定 Apple 蓝家族**，不是 §17 反对的
/// 「不做任何定制就直接用系统默认蓝」—— 定制点在于按本项目自定的对比度门槛
/// 把浅色版下压一档：
/// - 浅色 `#0066CC`（RGB 0 / 102 / 204）：Apple 蓝家族里深一档（Apple 网页链接常用的那档蓝），
///   与 `#007AFF` 同色相；
/// - 深色 `#0A84FF`（RGB 10 / 132 / 255）：Apple `systemBlue` 的深色档，与浅色版同色相。
///
/// 浅色为什么**不直接用**最字面的 `systemBlue #007AFF`：它压在本 App 页底 `#F2F2F7` 上
/// 只有 **3.60:1**、压在纯白上 **4.02:1**，都够不到本项目「小字 ≥ 4.5:1」的自定门槛
/// （旧暖珊瑚的注释正是拿这一条否决过系统蓝）。`#0066CC` 保持 Apple 蓝色相不变，
/// 把相对亮度从 0.21139 压到 0.13862，页底升到 4.99:1、纯白升到 5.57:1 —— 两全。
///
/// ## 对比度论证（下面每个数字都是算出来的，不是估的）
/// WCAG 2.1 相对亮度：`L = 0.2126·R' + 0.7152·G' + 0.0722·B'`；
/// 通道：`C' = C/12.92`（当 `C ≤ 0.03928`），否则 `C' = ((C + 0.055) / 1.055) ^ 2.4`
/// （`C` 是 8 位通道值除以 255）；对比度 = `(L 亮 + 0.05) / (L 暗 + 0.05)`。
///
/// 手算两版亮度：
/// - `#0066CC`：R 0 → `0.000000`；G 102/255 = 0.400 → `((0.400+0.055)/1.055)^2.4 = 0.132868`；
///   B 204/255 = 0.800 → `((0.800+0.055)/1.055)^2.4 = 0.603827`；
///   `L = 0.2126×0 + 0.7152×0.132868 + 0.0722×0.603827 = 0.138624`
/// - `#0A84FF`：R 10/255 = 0.039 → `0.003035`；G 132/255 = 0.518 → `0.230740`；
///   B 1.000 → `1.000000`；
///   `L = 0.2126×0.003035 + 0.7152×0.230740 + 0.0722×1.000000 = 0.237871`
/// - 参照底色：`#F2F2F7` L = 0.890969；`#1C1C1E` L = 0.011711；`#000000` L = 0；
///   `#FFFFFF` L = 1
///
/// | 场景 | 背景（L） | 前景（L） | 算式 | 比值 | ≥ 4.5:1 |
/// | --- | --- | --- | --- | --- | --- |
/// | 浅色·小字 | `#F2F2F7` 0.890969 | `#0066CC` 0.138624 | (0.890969+0.05)/(0.138624+0.05) | 4.99:1 | ✅ |
/// | 浅色·小字 | `#FFFFFF` 1.0 | `#0066CC` 0.138624 | (1.0+0.05)/(0.138624+0.05) | 5.57:1 | ✅ |
/// | 浅色·填充＋白字 | `#0066CC` 0.138624 | `#FFFFFF` 1.0 | (1.0+0.05)/(0.138624+0.05) | 5.57:1 | ✅ |
/// | 深色·小字 | `#000000` 0.0 | `#0A84FF` 0.237871 | (0.237871+0.05)/(0.0+0.05) | 5.76:1 | ✅ |
/// | 深色·小字 | `#1C1C1E` 0.011711 | `#0A84FF` 0.237871 | (0.237871+0.05)/(0.011711+0.05) | 4.66:1 | ✅ |
/// | 深色·填充＋深字 | `#0A84FF` 0.237871 | `#000000` 0.0 | (0.237871+0.05)/(0.0+0.05) | 5.76:1 | ✅ |
/// | 深色·填充＋白字 | `#0A84FF` 0.237871 | `#FFFFFF` 1.0 | (1.0+0.05)/(0.237871+0.05) | 3.65:1 | ❌ |
///
/// ### 最后一行为什么留着（是算出来无解，不是漏算）
/// `.borderedProminent` 配自定义 tint 时标签取 **白色**（明暗一致），于是
/// 「填充＋白字 ≥ 4.5」要求 `L ≤ 0.183333`（= 1.05/4.5 − 0.05）；
/// 而深色版还要当小字压在卡片 `#1C1C1E` 上，那要求 `L ≥ 0.227699`（= 4.5×0.061711 − 0.05）。
/// 两区间不相交（0.1833 < 0.2277）—— **任何单一深色值都不可能两头达标**。
/// 取舍：保小字可读（黑底 5.76 / 卡片 4.66），填充白字落在 3.65。
/// 这不是本方案独有的毛病：深色版用的就是 Apple `systemBlue` 深色档 `#0A84FF`，
/// 系统自己的深色 `.borderedProminent` 默认按钮（白字压 `#0A84FF`）算下来同样是 3.65:1。
/// 若某处填充要好上加好，应改**那一处**的标签色（本版填充配深字是 5.76:1），
/// 而不是再动这个令牌 —— 令牌只有一处，视图各有各的场景。
///
/// ### 参照：其它候选为什么没选（同一套算式）
/// - `#007AFF`（Apple 浅色 `systemBlue`，L = 0.21139）：页底 3.60:1、纯白 4.02:1 —— 不达标；
/// - 旧暖珊瑚 `#D1451F`（L = 0.17910）：纯白 4.58:1 达标，但压在本 App 页底 `#F2F2F7` 上
///   只有 4.11:1 —— 旧注释只报了白底那个数，页底色其实一直没进 4.5；
/// - `#FF9500`（系统橙，L = 0.42755）：页底 1.97:1 —— 更不可能。
///
/// ## 是否随外观切换：**会**，这是动态色（`UIColor { traitCollection in ... }`）
/// 旧注释那句「单值不随明暗外观切换」对新方案已经不成立，新理由是算出来的：
/// 一次性注入的单一色值要同时满足「浅色页底当小字够暗」与「深色页底当小字够亮」，即
/// `L ≤ 0.159104`（`#F2F2F7` 上 ≥ 4.5）且 `L ≥ 0.175000`（`#000000` 上 ≥ 4.5）——
/// 区间为空（0.1591 < 0.1750），**这样的颜色不存在**。
/// 蓝色在这个方向尤其吃暗亏：亮度公式里 B 的系数只有 0.0722（R 0.2126 / G 0.7152），
/// 所以就算把蓝拉到最亮，纯蓝 `#0000FF` 的 `L = 0.0722×1 = 0.0722`，
/// 压在纯黑上也只有 (0.0722+0.05)/0.05 = **2.44:1**；要靠加绿通道补亮度，
/// 色相立刻从蓝偏向青，就不再是「Apple 风格的蓝」了。
/// 因此只有分外观两版才可能两边都达标：浅色版负责「够暗」（4.99 / 5.57），
/// 深色版负责「够亮」（5.76 / 4.66）。`UIColor` 的 trait 闭包是 iOS 13+ API
/// （本项目最低 iOS 17），SwiftUI 按当前外观解析，所以 `RootView` 里的
/// `.tint(AppTheme.accent)` 保持单行注入，**视图层不做任何明暗判断**。
enum AppTheme {
    /// 品牌强调色：Apple 蓝家族动态色 —— 浅色 `#0066CC`（RGB 0 / 102 / 204），
    /// 深色 `#0A84FF`（RGB 10 / 132 / 255）。对比度论证见类型文档。
    static let accent = Color(uiColor: UIColor { traits in
        traits.userInterfaceStyle == .dark
            ? UIColor(red: 10.0 / 255.0, green: 132.0 / 255.0, blue: 255.0 / 255.0, alpha: 1)
            : UIColor(red: 0.0 / 255.0, green: 102.0 / 255.0, blue: 204.0 / 255.0, alpha: 1)
    })

    /// 卡片化视觉语言（U1-1）：**浅色底 + 卡面 + 细微分隔线**。
    ///
    /// ## 为什么放在这里
    /// `DesignTokens.swift` 只管尺度、不放颜色（那是它自己的约定）。颜色统一由 `AppTheme` 定义，
    /// 避免出现第二个颜色真相源。
    ///
    /// ## 为什么全用语义系统色
    /// skill §6 / §17「忽略深色模式」：语义色会随明暗外观自动适配。
    /// - `page` 浅色下是系统分组灰（≈ `#F2F2F7`），深色下自动转黑；
    /// - `card` 浅色下是白，压在页面灰底上形成**一级层次**（卡片与页面同色是 U0-3 的旧取舍，
    ///   U1-1 明确要求卡片化，所以卡面重新与页面分开）；深色下 `card` ≈ `#1C1C1E`，
    ///   正是上面 `accent` 深色版对照的那个次级容器底色；
    /// - 细微分隔线**不在这里定义**：一律用系统 `Divider()`（本身就是发丝级 + 自动配色），
    ///   不要再加一个色值令牌去手绘 1px 线。
    ///
    /// → 因此**不要**在这里写 `Color(white:)` / 十六进制值。
    enum Surface {
        /// 页面底色。
        static let page = Color(.systemGroupedBackground)
        /// 卡面（列表行卡片、搜索结果卡、章节行卡）。
        static let card = Color(.secondarySystemGroupedBackground)
        /// 卡面上的次级区块（卡片内再嵌一层）。
        static let inset = Color(.tertiarySystemGroupedBackground)
    }
}
