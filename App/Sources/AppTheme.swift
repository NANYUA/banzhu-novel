import SwiftUI

/// 品牌视觉基准：**唯一**的品牌强调色定义处。
///
/// ## 为什么有这一层
/// 改造前全应用没有任何品牌色 —— 强调色一律是系统默认蓝（HIG §17「到处默认蓝」），
/// 再散落成 `Color.accentColor` / `.tint(.green)` 各写各的。
/// 现在品牌强调色只在这里定义一次，其余文件引用 `AppTheme.accent`，
/// 不在视图里另写色值（§15 设计令牌）。
///
/// ## 取值：暖珊瑚红 `#D1451F`
/// §2 / §6：中性底 + **单一暖色**强调，不做紫蓝渐变、不做霓虹。
/// 这个值是按对比度算出来的，不是随手取的：
/// - 白底当小字用 = **4.58:1**（正文要求 ≥ 4.5:1，通过）
/// - 纯黑底当小字用 = **4.58:1**（通过）
/// - 白字压在它上面（`.borderedProminent` 填充）= **4.58:1**（通过）
///
/// 参照：系统蓝 `#007AFF` 白底只有 4.0:1，系统橙 `#FF9500` 只有 2.2:1；
/// 更浅的暖珊瑚 `#E85D3A` 只有 3.47:1 —— 小字不达标，所以没采用。
///
/// 单值不随明暗外观切换：这个强调色同时要当「按钮填充」和「小字 / 图标前景」，
/// 深色模式一旦调亮，压在它上面的白字会掉到 2.5:1 以下（读不清的按钮文字比
/// 偏沉的按钮更糟）。若产品决定深色模式要更亮的一版，再加动态色。
enum AppTheme {
    /// 品牌强调色：暖珊瑚红 `#D1451F`（= RGB 209 / 69 / 31）。
    static let accent = Color(red: 209.0 / 255.0, green: 69.0 / 255.0, blue: 31.0 / 255.0)

    /// 卡片化视觉语言（U1-1）：**浅色底 + 卡面 + 细微分隔线**。
    ///
    /// ## 为什么放在这里
    /// `DesignTokens.swift` 只管尺度、不放颜色（那是它自己的约定）。颜色统一由 `AppTheme` 定义，
    /// 避免出现第二个颜色真相源。
    ///
    /// ## 为什么全用语义系统色
    /// skill §6 / §17「忽略深色模式」：语义色会随明暗外观自动适配。
    /// - `page` 浅色下是系统分组灰（≈ `#F2F2F7`），深色下自动转黑；
    /// - `card` 浅色下是白，压在页面灰底上形成**一级层次**（卡片与页面同色是 U0-3 的旧取舍，
    ///   U1-1 明确要求卡片化，所以卡面重新与页面分开）；
    /// - `separator` 是系统分隔线色，本身就是 1px 发丝级，符合「细微分隔线」。
    ///
    /// → 因此**不要**在这里写 `Color(white:)` / 十六进制值。
    enum Surface {
        /// 页面底色。
        static let page = Color(.systemGroupedBackground)
        /// 卡面（列表行卡片、搜索结果卡、章节行卡）。
        static let card = Color(.secondarySystemGroupedBackground)
        /// 卡面上的次级区块（卡片内再嵌一层）。
        static let inset = Color(.tertiarySystemGroupedBackground)
        /// 细微分隔线。
        static let separator = Color(.separator)
    }
}
