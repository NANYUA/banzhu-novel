import CoreGraphics

/// 间距 / 圆角令牌：本应用**唯一**的尺度定义处。
///
/// ## 为什么有这一层
/// 改造前 `App/Sources` 里同时出现过 2 / 3 / 4 / 6 / 7 / 8 / 10 / 12 / 14 / 16 十种间距，
/// 以及 6 / 8 / 16 三种圆角 —— 全凭手感，没有体系（HIG §17「间距随机、无体系」）。
/// 现在只允许从下面这组系统协调值里取值，新代码写令牌，不写新的魔数。
///
/// ## 什么算死代码（判据）
/// **尺度刻度（`Spacing` / `Radius`）是一把尺子**：某个刻度暂时没有引用不算死代码，
/// 只是当前没用到，留着不影响任何真相源。
/// **语义角色型令牌（颜色 / 材质）0 引用必须删** —— 多一个「N 选 1」的角色就多一个真相源
/// （`Surface.separator` 即按此删掉）。
///
/// ## 刻度与映射
/// Apple 不强制 8pt 网格（那是 Material 的概念），用的是**协调值**：
/// 间距 `8 / 12 / 16 / 20 / 24 / 32`，另加一个贴在内容内部的 `4`；圆角 `6 / 12 / 18`（`6` 见 `Radius.xs`）。
/// 历史散值已按下表机械映射（只对齐尺度，不改视觉语言）：
///
/// | 原值 | 现取值 |
/// | --- | --- |
/// | 间距 2 / 3 / 4 | 4 |
/// | 间距 6 / 7 | 8 |
/// | 间距 10 | 12 |
/// | 间距 14 | 16 |
/// | 圆角 6 / 8（卡片类） | 12 |
/// | 圆角 16（大容器类） | 18 |
///
/// 颜色**不放这里**：品牌强调色在 `AppTheme.swift` 单点定义，
/// 两个文件各管一件事，避免出现第二个颜色真相源。
enum DesignTokens {
    /// 间距刻度（pt）。
    enum Spacing {
        /// 4 —— 紧贴内容的微间距（行内元素之间）。
        static let xxs: CGFloat = 4
        /// 8 —— 同一区块内元素之间。
        static let xs: CGFloat = 8
        /// 12 —— 常规元素间隔 / 行内边距。
        static let sm: CGFloat = 12
        /// 16 —— 标准内容页边距（iPhone）。
        static let md: CGFloat = 16
        /// 20 —— 区块之间。
        static let lg: CGFloat = 20
        /// 24 —— 大区块之间。
        static let xl: CGFloat = 24
        /// 32 —— 空状态级别的留白。
        static let xxl: CGFloat = 32
    }

    /// 圆角刻度（pt）。
    ///
    /// 卡片语言只有两档：`sm`(12) 用于卡片 / 封面 / 缩略图 / 列表行，
    /// `lg`(18) 用于大容器与浮层（阅读页材质控制栏、sheet 内容块）。
    /// 另加 `xs`(6)：**不参与卡片语言**，专供嵌在圆角容器内的小控件强调层（推导见下）。
    /// 原先的 `xs`(8) 与 `md`(16) 全仓 0 引用、封面实际一律走 `sm` —— 已删
    /// （现在的 `xs` 是重新定义的 6，与当初那个 8 无关）。
    enum Radius {
        /// 6 —— **嵌在圆角容器内**的小控件强调层（= 父容器圆角 − 容器内缩量）。
        ///
        /// 几何推导：父容器圆角 `Radius.lg`(18)，容器内的小控件四周内缩 `Spacing.sm`(12)，
        /// 故强调层圆角最多只能取 `18 - 12 = 6`，才能**完全**落在父容器的圆角之内；
        /// 取 `sm`(12) 只是缓解 —— 对角方向仍会露出约 2.5pt 方角。
        /// 用途限定为这类「父容器圆角 - 内缩量」的强调层；卡片 / 封面 / 缩略图仍用 `sm`。
        /// （阅读页控制栏改成**通栏玻璃**后，栏内按钮不再被父容器圆角裁切、改用 `sm`；
        /// 本刻度作为尺子保留。）
        static let xs: CGFloat = 6
        /// 12 —— **卡片默认**：列表行卡片、搜索结果卡、章节行卡片、封面 / 缩略图。
        static let sm: CGFloat = 12
        /// 18 —— 大容器 / 浮层（阅读页材质控制栏、sheet 内容块）。
        static let lg: CGFloat = 18
    }
}
